  var DENTAL_BANDS = [['75% - 100%', 0.75], ['60% - 74%', 0.60], ['50% - 59%', 0.50], ['35% - 49%', 0.35]];

  /** The participation labels the tool allows (Tables BP1:BP4 <- BS133:BS135 / BQ133:BQ136, Michigan = Restricted). */
  function dentalParticipationOptions(eligible, contribution) {
    if (eligible < 5) return ['100%'];
    if (contribution === 'vol' && eligible >= 10) return ['35% - 49%', '50% - 59%', '60% - 74%', '75% - 100%'];
    return ['50% - 59%', '60% - 74%', '75% - 100%'];
  }

  /**
   * Dental and vision enrollment with no headcount is ASSUMED from who pays, never asked (David
   * 11-02: "ask if it is voluntary or Employer paid. if employer paid assume 50%+ enrollment, note
   * that assumption"): employer paid = 50% - 59% (dental: the highest rate inside 50%+; vision's
   * band is 50% - 100%); voluntary = the lowest MetLife allows (dental 35% - 49% at 10+ eligible,
   * else 50% - 59%; vision 25% - 49% at 10+, else 50% - 100%). Either way at least 5 enroll
   * (MetLife's minimum). -> { label, pct, text }; the text goes on the quote as the assumption.
   */
  function assumedShare_(line, ctx) {
    var vol = ctx.contribution === 'vol';
    var ten = ctx.inputs.groupSize >= 10;
    var lowVol = vol && ten;
    var label = line === 'Dental' ? (lowVol ? '35% - 49%' : '50% - 59%') : (lowVol ? '25% - 49%' : '50% - 100%');
    var pct = line === 'Dental' ? (lowVol ? 35 : 50) : (lowVol ? 25 : 50);
    var band = label === '50% - 100%' ? '' : ', at MetLife\'s ' + label.replace(' - ', ' to ') + ' rate';
    return { label: label, pct: pct, text: 'Priced assuming at least ' + pct + '% of eligible employees enroll, and at least 5 (' +
      (vol ? 'voluntary: the lowest MetLife allows' : 'employer paid') + ')' + band + '. MetLife sets the final rate from the actual enrollment.' };
  }

  /** The least enrolled the assumption means, for a rule that counts enrollees (at least 5). */
  function assumedEnrolled_(line, ctx) {
    return Math.max(5, Math.ceil(assumedShare_(line, ctx).pct / 100 * ctx.inputs.groupSize));
  }

  /**
   * Participation = enrolled / eligible ("taking valid waivers into account": no waivers yet).
   * With no headcount, assumed from who pays (assumedShare_), and said.
   */
  function dentalParticipation_(ctx) {
    var eligible = ctx.inputs.groupSize;
    var allowed = dentalParticipationOptions(eligible, ctx.contribution);
    if (ctx.participation) return { label: ctx.participation }; // the referee sets the tool's label directly
    if (!ctx.enrolled) {
      var a = assumedShare_('Dental', ctx);
      return { label: allowed[0] === '100%' ? '100%' : a.label, assumed: a.text };
    }
    var r = ctx.enrolled / eligible;
    var band = DENTAL_BANDS.filter(function (b) { return r >= b[1]; })[0];
    if (!band || allowed.indexOf(band[0]) < 0) {
      return { why: 'MetLife dental needs ' + (allowed[0] === '35% - 49%' ? '35%' : '50%') + ' or more of eligible employees enrolled (' +
        ctx.enrolled + ' of ' + eligible + ').' };
    }
    return { label: band[0] };
  }

  function visionParticipation_(ctx) {
    if (ctx.participation) return { label: ctx.participation }; // the referee sets the tool's label directly
    if (!ctx.enrolled) {
      var a = assumedShare_('Vision', ctx);
      return { label: a.label, assumed: a.text };
    }
    var r = ctx.enrolled / ctx.inputs.groupSize;
    if (r >= 0.5) return { label: '50% - 100%' };
    if (r >= 0.25) {
      // The tool's participation table (EO23:ER32) has no 25% - 49% factor below vision25From lives.
      if (ctx.inputs.groupSize < rules_().vision25From) return { why: 'MetLife vision needs 50% or more enrolled for a group this size.' };
      return { label: '25% - 49%' };
    }
    return { why: 'MetLife vision needs 25% or more of eligible employees enrolled (' + ctx.enrolled + ' of ' + ctx.inputs.groupSize + ').' };
  }

