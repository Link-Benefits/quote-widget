  /** '' when MetLife can rate the group, else why not (Dental-Vision E36 / E83 rules for Michigan). */
  function groupBlock_(inputs, sicKey) {
    var r = rules_();
    if (r.zip3.indexOf(String(inputs.zip || '').slice(0, 3)) < 0) return 'MetLife rates here are for Michigan ZIP codes.';
    if (inputs.groupSize < 5) return 'MetLife needs at least 5 eligible lives in Michigan.';
    if (inputs.groupSize > 99) return 'This MetLife tool covers groups up to 99 eligible lives.';
    var s = r.sic[String(inputs.sic || '').replace(/^0+/, '')];
    if (!s) return 'SIC ' + inputs.sic + ' is not on MetLife\'s allowable SIC list.';
    var f = s.charAt(r.lines.indexOf(sicKey));
    if (f === 'x') return 'MetLife does not offer this coverage for SIC ' + inputs.sic + '.';
    if (f === 'm') return 'MetLife prices SIC ' + inputs.sic + ' by request.';
    return '';
  }

