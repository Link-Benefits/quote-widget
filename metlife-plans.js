  /**
   * Enrollment for a life or disability design (David 11-02: "build it that way"). Employer-paid
   * (100%) asks nothing: every eligible employee is covered, which is what employer-paid means, and
   * MetLife's 5-life minimum is its eligibility. A contributory or voluntary design asks ONE yes/no at
   * its own minimum (ASKS minContrib / minVol, asked only while such a design is ticked: `uses`); "no"
   * is MetLife's reason not to quote, so it is asked, never assumed.
   * need = { key, pct, count, what } (key '' = employer-paid).
   */
  function needs_(g, ctx, need) {
    if (!need.key) return;
    g.uses.push(need.key);
    var v = ((ctx.answers && ctx.answers.line) || {})[need.key];
    if (!v) g.missing.push(need.key);
    else if (v === 'no') {
      g.whys.push(need.what + ' needs ' + need.pct + '% of eligible employees, and at least ' + need.count + ', enrolled.');
    }
  }

  /** The question for a design's minimum, in the agent's words (from the same numbers as the rule). */
  function minLabel_(need) {
    return 'Will at least ' + need.pct + '% of eligible employees, and at least ' + need.count + ', enroll in ' +
      need.what.charAt(0).toLowerCase() + need.what.slice(1) + '?';
  }

  function finish_(g, later) {
    if (g.whys.length) return { why: g.whys.join(' '), missing: g.missing, uses: g.uses };
    return { later: g.forMetLife ? 'MetLife prices this SIC itself: the design goes to MetLife with the request.' : later,
      missing: g.missing, uses: g.uses };
  }

