  // The tool's Life-Disability sheet. Employer-paid basic life, STD and LTD are rated from each
  // person's age and salary (the census). Voluntary STD and LTD are quoted as age-band rates, but
  // the tool BUILDS those bands from the same census (it reslopes them over the group's ages and
  // pay, and shows none until the rows are filled: found 10-31), so they need it too. Only
  // supplemental life is a fixed table (by the SIC's level). The prices come from the tool's own
  // formulas (metlife-ld-engine.js, refereed against Excel) through lifeQuote() in the private pack, AFTER the
  // form is sent (the quote builder), so in the widget these offerings are `later`: it asks no
  // census question (David, 2026-10-30). The option lists are the tool's own (Tables, cells
